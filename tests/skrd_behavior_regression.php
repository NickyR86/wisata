<?php
use App\Support\FinanceDocument;
require __DIR__.'/finance_location_regression.php';
$r['location_id']=1;
$r['bill']=null;
$r['templates']['skrd']['attention']='';
$r['templates']['skrd']['payer']='Identitas lama';
$r['skrd_source']=FinanceDocument::source($r);
$r['name']='Pemohon baru'; $r['date']='2026-11-12'; $r['days']=3;
$changes=FinanceDocument::sourceChanges($r);
check(isset($changes['name'],$changes['date'],$changes['days']), 'Source differences missing');
$doc=FinanceDocument::data($r,'skrd',true);
check(str_contains($doc['payer'],'Pemohon baru'), 'Identity not synchronized');
check($doc['description']==='Uraian tersimpan', 'Narrative overwritten');
check($doc['attention']==='', 'Empty attention restored incorrectly');
$r['bill']=['subtotal'=>2400000,'percent'=>25,'total'=>1800000];
FinanceDocument::freezeSkrd($r,'Penerbitan uji');
$original=FinanceDocument::data($r,'skrd');
$r['name']='Pemohon berubah lagi'; $r['days']=5;
$r['templates']['skrd']['description']='Revisi uraian';
check(FinanceDocument::data($r,'skrd')===$original, 'Issued snapshot changed');
check(FinanceDocument::data($r,'skrd',true)['source']['days']===5, 'Revision does not show latest source');
FinanceDocument::freezeSkrd($r,'Revisi beralasan');
check(count($r['skrd_versions'])===2 && $r['skrd_versions'][0]['data']===$original, 'Old version lost');
check(FinanceDocument::data($r,'skrd')['description']==='Revisi uraian', 'Revision not published');
check(FinanceDocument::data($r,'skrd')['total']===1800000, 'Revision changed invoice');
check(FinanceDocument::sourceChanges($r)===[], 'Source not acknowledged');
$r['bill']=null; unset($r['skrd_snapshot']);
$r['templates']['skrd']['rows']=[['code'=>'1','label'=>'Uji','amount'=>3000000]];
$r['templates']['skrd']['assessment']=['rate'=>320000,'note'=>'Tarif tersimpan'];
$r['templates']['skrd']['rental_date']='2026-12-15';
$doc=FinanceDocument::data($r,'skrd',true);
check($doc['base']==1600000 && (float)$doc['total']===1200000.0,'Draft totals do not follow assessment with 25% relief');
check($doc['words']==='satu juta dua ratus ribu rupiah','Words do not follow assessment amount');
check($doc['rental_date']==='2026-12-15','Rental date override lost');
unset($r['templates']['skrd']['rental_date']);
check(FinanceDocument::data($r,'skrd',true)['rental_date']===$r['date'],'Default rental date not synchronized');

echo "PASS: $checks total location and SKRD behavior checks\n";
